use super::models::FileRecord;
use std::fs::File;
use std::io::{BufRead, BufReader};
use std::path::Path;

pub fn parse_wiztree_csv(csv_path: &Path, max_records: usize) -> Result<Vec<FileRecord>, String> {
    let file = File::open(csv_path).map_err(|e| format!("Failed to open CSV file: {e}"))?;
    let mut reader = BufReader::new(file);

    let mut first_line = String::new();
    reader
        .read_line(&mut first_line)
        .map_err(|e| format!("Failed to read CSV header: {e}"))?;

    // Strip UTF-8 BOM if present
    let clean_first = first_line.trim_start_matches('\u{feff}').trim_end();

    // If first line is WizTree banner, second line is the actual CSV header
    let mut csv_content = String::new();
    if clean_first.starts_with("Generated by WizTree") {
        // Leave cursor at line 2 for csv reader
    } else {
        csv_content.push_str(clean_first);
        csv_content.push('\n');
    }

    let mut csv_reader = csv::ReaderBuilder::new()
        .has_headers(true)
        .flexible(true)
        .from_reader(reader);

    let mut records = Vec::new();

    for result in csv_reader.records() {
        let record = match result {
            Ok(r) => r,
            Err(_) => continue,
        };

        let file_path = match record.get(0) {
            Some(p) if !p.trim().is_empty() => p.trim().to_string(),
            _ => continue,
        };

        let size: u64 = record.get(1).and_then(|s| s.parse().ok()).unwrap_or(0);
        let allocated: u64 = record.get(2).and_then(|s| s.parse().ok()).unwrap_or(0);
        let modified = record.get(3).unwrap_or("").to_string();
        let attrs: u32 = record.get(4).and_then(|s| s.parse().ok()).unwrap_or(0);

        let is_folder = (attrs & 16) != 0;
        let name = Path::new(&file_path)
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or(&file_path)
            .to_string();

        records.push(FileRecord {
            path: file_path,
            name,
            size,
            allocated,
            modified,
            attributes: attrs,
            is_folder,
        });

        if max_records > 0 && records.len() >= max_records {
            break;
        }
    }

    Ok(records)
}
